def compute_metrics() -> AutomationMetrics:
    """Compute automation metrics."""
    metrics = AutomationMetrics(
        timestamp=datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    )

    for name, automated in EXPECTED_OUTPUTS:
        path = _DIST_DIR / name
        exists = path.exists()
        size = path.stat().st_size if exists else 0
        mtime = None
        if exists:
            mtime = datetime.fromtimestamp(
                path.stat().st_mtime, tz=timezone.utc
            ).strftime("%Y-%m-%dT%H:%M:%SZ")

        metric = OutputMetric(
            name=name,
            path=str(path),
            exists=exists,
            size_bytes=size,
            last_modified=mtime,
            automated=automated,
        )
        metrics.outputs.append(metric)
        metrics.total_outputs += 1
        if automated:
            metrics.automated_outputs += 1
        else:
            metrics.manual_outputs += 1
        if not exists:
            metrics.missing_outputs += 1

    # Health status.
    try:
        from ..data.registry import TOPICS
        from .health_check import run_health_checks
        checks = run_health_checks(TOPICS)
        errors = sum(1 for c in checks if c.status == "error")
        metrics.health_status = "error" if errors > 0 else "ok"
    except Exception:
        metrics.health_status = "unknown"

    return metrics


def format_metrics_report(metrics: AutomationMetrics) -> str:
    """Human-readable metrics report."""
    lines = [
        "Automation Metrics",
        "=" * 40,
        f"Timestamp: {metrics.timestamp}",
        f"Total outputs: {metrics.total_outputs}",
        f"Automated: {metrics.automated_outputs}",
        f"Manual: {metrics.manual_outputs}",
        f"Missing: {metrics.missing_outputs}",
        f"Automation rate: {metrics.automation_rate}",
        f"Health: {metrics.health_status}",
        "",
        "Outputs:",
    ]

    for o in metrics.outputs:
        status = "✓" if o.exists else "✗"
        auto = "auto" if o.automated else "manual"
        size = f"{o.size_bytes:,}B" if o.exists else "—"
        lines.append(f"  {status} {o.name:30} {auto:6} {size:>10}")

    if not metrics.has_all_outputs:
        lines.append("")
        lines.append("WARNING: Missing outputs. Run 'python build.py' first.")

    return "\n".join(lines)


if __name__ == "__main__":
    metrics = compute_metrics()
    print(format_metrics_report(metrics))

    # Write metrics to dist/.
    _DIST_DIR.mkdir(parents=True, exist_ok=True)
    out = _DIST_DIR / "automation-metrics.json"
    out.write_text(
        json.dumps(metrics.to_dict(), indent=2, ensure_ascii=False),
        encoding="utf-8")
    print(f"\nautomation-metrics.json -> {out}")
