"""Automation metrics — measure before trusting.

Tracks:
  - Which operations are automated vs manual
  - Build completeness (all expected outputs present)
  - Health check integration (pass/fail counts)
  - Freshness (when was each output last generated)

Usage:
    python -m universe_explorer.reader.automation_metrics
"""

from __future__ import annotations

import json
import os
import time
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, List, Optional

_DIST_DIR = Path(__file__).parent.parent.parent / "dist"


@dataclass
class OutputMetric:
    """Metric for one output file."""

    name: str
    path: str
    exists: bool = False
    size_bytes: int = 0
    last_modified: Optional[str] = None
    automated: bool = False  # generated by build.py

    def to_dict(self) -> dict:
        return {
            "name": self.name,
            "path": self.path,
            "exists": self.exists,
            "size_bytes": self.size_bytes,
            "last_modified": self.last_modified,
            "automated": self.automated,
        }


@dataclass
class AutomationMetrics:
    """Complete automation metrics."""

    timestamp: str = ""
    total_outputs: int = 0
    automated_outputs: int = 0
    manual_outputs: int = 0
    missing_outputs: int = 0
    health_status: str = "unknown"
    outputs: List[OutputMetric] = field(default_factory=list)

    def to_dict(self) -> dict:
        return {
            "timestamp": self.timestamp,
            "total_outputs": self.total_outputs,
            "automated_outputs": self.automated_outputs,
            "manual_outputs": self.manual_outputs,
            "missing_outputs": self.missing_outputs,
            "health_status": self.health_status,
            "automation_rate": f"{self.automated_outputs}/{self.total_outputs}",
            "outputs": [o.to_dict() for o in self.outputs],
        }

    @property
    def is_fully_automated(self) -> bool:
        return self.automated_outputs == self.total_outputs

    @property
    def automation_rate(self) -> str:
        return f"{self.automated_outputs}/{self.total_outputs}"

    @property
    def has_all_outputs(self) -> bool:
        return self.missing_outputs == 0


